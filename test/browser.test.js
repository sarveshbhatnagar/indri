import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import { createApp } from '../src/server.js';

test('browser: diagrams, sketch elements, comments, replies, resolution and draft preservation', async () => {
  const { app, store, mcp } = createApp({ dbPath: ':memory:' });
  const http = app.listen(0, '127.0.0.1'); await new Promise(resolve => http.once('listening', resolve));
  const base = `http://127.0.0.1:${http.address().port}`;
  const browser = await chromium.launch({ channel: 'chromium' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', err => errors.push(err.message));
    const requests = []; page.on('request', req => requests.push(new URL(req.url()).pathname));
    const architecture = store.create(JSON.parse(await readFile(new URL('../examples/architecture.json', import.meta.url))));
    const sketch = store.create(JSON.parse(await readFile(new URL('../examples/login-sketch.json', import.meta.url))));
    await page.goto(base);
    await expect(page.getByRole('link', { name: /How Indri connects/ })).toBeVisible();
    requests.length = 0;
    await page.getByRole('link', { name: /How Indri connects/ }).click();
    await page.getByRole('button', { name: 'Comment on Indri MCP tools', exact: true }).click();
    await expect(page.locator('#view-label')).toHaveText('Diagram review');
    await expect(page.getByRole('link')).toHaveCount(0);
    await expect(page.getByText(sketch.graph.title, { exact: true })).toHaveCount(0);
    assert.ok(!requests.includes('/api/diagrams'));
    assert.ok(!requests.some(path => path.includes(sketch.id)));
    await expect(page.locator('#selection')).toContainText('src/mcp.js');
    await expect(page.getByRole('button', { name: 'Move view', exact: true })).toHaveAttribute('aria-pressed', 'true');
    const mcpNode = page.getByRole('button', { name: 'Comment on Indri MCP tools', exact: true });
    const beforePan = await mcpNode.boundingBox();
    await page.mouse.move(beforePan.x + beforePan.width / 2, beforePan.y + beforePan.height / 2);
    await page.mouse.down();
    await page.mouse.move(beforePan.x + beforePan.width / 2 + 60, beforePan.y + beforePan.height / 2 - 40, { steps: 6 });
    await page.mouse.up();
    const afterPan = await mcpNode.boundingBox();
    assert.ok(Math.abs(afterPan.x - beforePan.x - 60) < 1);
    assert.ok(Math.abs(afterPan.y - beforePan.y + 40) < 1);
    await expect(page.locator('#selection')).toContainText('src/mcp.js');
    await expect(page.locator('.selecting')).toHaveCount(0);
    assert.equal(store.get(architecture.id).comments.length, 0);
    await page.getByRole('button', { name: 'Fit', exact: true }).click();
    assert.ok((await page.locator('#drawing').getAttribute('viewBox')).startsWith('0 0 '));
    await page.getByLabel('Feedback', { exact: true }).fill('<img src=x onerror=alert(1)> Explain validation here.');
    await page.getByRole('button', { name: 'Leave comment' }).click();
    await expect(page.locator('.message p')).toHaveText('<img src=x onerror=alert(1)> Explain validation here.');
    assert.equal(await page.locator('.message img').count(), 0);
    await page.getByRole('button', { name: 'Reply', exact: true }).click();
    await page.getByLabel('Reply', { exact: true }).fill('Validation happens at the tool boundary.');
    await page.getByRole('button', { name: 'Send reply', exact: true }).click();
    await expect(page.locator('.message')).toHaveCount(2);
    await page.getByRole('button', { name: 'Resolve', exact: true }).click();
    await expect(page.locator('#open-count')).toHaveText('0 open');
    await page.getByLabel('Include resolved').check();
    await page.getByRole('button', { name: 'Reopen', exact: true }).click();
    assert.equal(store.get(architecture.id).comments[0].status, 'open');
    await page.getByRole('button', { name: 'Comment on whole diagram', exact: true }).click();
    await page.getByRole('button', { name: 'Comment on connection: draw / read feedback', exact: true }).focus();
    await page.keyboard.press('Enter');
    await expect(page.locator('#selection')).toContainText('Connection · draw');
    await expect(page.locator('#selection')).not.toContainText('undefined');
    await page.screenshot({ path: '/tmp/indri-diagram.png', fullPage: true });
    await page.goto(`${base}/?diagram=${sketch.id}`);
    await expect(page.locator('#kind-label')).toHaveText('ROUGH SKETCH / UX REVIEW');
    await page.getByRole('button', { name: 'Comment on Sign in →', exact: true }).click();
    await page.getByLabel('Feedback', { exact: true }).fill('Use a magic link instead.');
    await page.getByRole('button', { name: 'Leave comment' }).click();
    await expect(page.locator('.message p')).toHaveText('Use a magic link instead.');
    assert.equal(store.get(sketch.id).comments[0].target.id, 'submit');
    await page.getByLabel('Feedback', { exact: true }).fill('Unsaved draft must survive.');
    await page.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(page.getByLabel('Feedback', { exact: true })).toHaveValue('Unsaved draft must survive.');
    await page.getByLabel('Feedback', { exact: true }).fill('');
    await page.getByRole('button', { name: 'Zoom in' }).click();
    await page.locator('#canvas').evaluate(canvas => { canvas.scrollTop = 100; });
    const beforeFieldPan = await page.getByRole('button', { name: 'Comment on Email address', exact: true }).boundingBox();
    await page.mouse.move(beforeFieldPan.x + 30, beforeFieldPan.y + 20);
    await page.mouse.down();
    await page.mouse.move(beforeFieldPan.x + 70, beforeFieldPan.y + 30, { steps: 4 });
    await page.mouse.up();
    assert.equal(store.get(sketch.id).comments.length, 1);
    await page.getByRole('button', { name: 'Select area', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Select area', exact: true })).toHaveAttribute('aria-pressed', 'true');
    const field = await page.getByRole('button', { name: 'Comment on Email address', exact: true }).boundingBox();
    await page.mouse.move(field.x + field.width + 5, field.y + field.height + 5);
    await page.mouse.down();
    await page.mouse.move(field.x - 5, field.y - 5, { steps: 8 });
    await page.mouse.up();
    await expect(page.locator('#selection')).toContainText('Selected area');
    await expect(page.getByLabel('Feedback', { exact: true })).toBeFocused();
    await expect(page.getByRole('button', { name: 'Move view', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await page.getByLabel('Feedback', { exact: true }).fill('Make this field wider.');
    await page.getByRole('button', { name: 'Leave comment' }).click();
    await expect(page.locator('.message p')).toHaveText('Make this field wider.');
    const area = store.get(sketch.id).comments[1];
    assert.equal(area.target.type, 'region');
    assert.ok(area.context.nodes.some(n => n.id === 'email' && n.selected));
    assert.ok(Math.abs(area.target.width - (field.width + 10) / 1.25) < 3);
    await page.reload();
    await page.getByRole('button', { name: 'Open area comment 2', exact: true }).click();
    await expect(page.locator('.message p')).toHaveText('Make this field wider.');
    await page.screenshot({ path: '/tmp/indri-area.png', fullPage: true });
    const current = store.get(sketch.id);
    store.update(sketch.id, { expected_revision: 1, graph: { ...current.graph, title: 'Updated sign-in sketch', nodes: current.graph.nodes.map(n => n.id === 'email' ? { ...n, label: 'Your email', x: 80 } : n) } });
    await page.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(page.locator('#title')).toHaveText('Updated sign-in sketch');
    await expect(page.locator('.thread-meta')).toContainText('Earlier drawing');
    await expect(page.getByRole('button', { name: 'Open area comment 2', exact: true })).toHaveCount(0);
    await page.getByLabel('Diagram version').selectOption('1');
    await expect(page.locator('#title')).toHaveText('Rough sketch · sign-in experience');
    await expect(page.getByRole('button', { name: 'Leave comment' })).toBeDisabled();
    await expect(page.getByRole('button', { name: 'Select area', exact: true })).toBeDisabled();
    const oldView = await page.locator('#drawing').getAttribute('viewBox');
    const oldCanvas = await page.locator('#canvas').boundingBox();
    await page.mouse.move(oldCanvas.x + 40, oldCanvas.y + 80); await page.mouse.down();
    await page.mouse.move(oldCanvas.x + 80, oldCanvas.y + 100, { steps: 4 }); await page.mouse.up();
    assert.notEqual(await page.locator('#drawing').getAttribute('viewBox'), oldView);
    await page.getByLabel('Diagram version').selectOption('2');
    await expect(page.locator('#title')).toHaveText('Updated sign-in sketch');
    await page.getByRole('button', { name: 'Area 2 · Email address', exact: true }).click();
    await expect(page.getByLabel('Diagram version')).toHaveValue('1');
    await page.getByRole('button', { name: 'Open area comment 2', exact: true }).click();
    await expect(page.locator('.message p')).toHaveText('Make this field wider.');
    await page.getByRole('button', { name: 'Restore as new version' }).click();
    await expect(page.locator('#revision')).toHaveText('Revision 3');
    assert.equal(store.get(sketch.id, 2).graph.title, 'Updated sign-in sketch');
    assert.equal(store.get(sketch.id).comments.length, 2);
    await page.screenshot({ path: '/tmp/indri-sketch.png', fullPage: true });
    const canvas = await page.locator('#canvas').boundingBox();
    await page.mouse.click(canvas.x + canvas.width - 80, canvas.y + 170);
    await expect(page.locator('#selection')).toContainText('Whole diagram');
    await page.getByRole('button', { name: 'Select area', exact: true }).click();
    await page.mouse.click(canvas.x + canvas.width - 80, canvas.y + 170);
    await expect(page.locator('#selection')).toContainText('Selected area');
    await expect(page.getByLabel('Feedback', { exact: true })).toBeFocused();
    await page.keyboard.press('Escape');
    await expect(page.locator('#selection')).toContainText('Whole diagram');
    await expect(page.getByRole('button', { name: 'Move view', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByRole('button', { name: 'Leave comment' })).toBeVisible();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await mcp.close(); await new Promise(resolve => http.close(resolve)); store.close(); }
});
